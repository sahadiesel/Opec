/**
 * คำนวณภาษีเงินได้บุคคลธรรมดา รายปี จากฐานเงินได้สุทธิ (หลังหักลดหย่อนแล้ว — ฝั่งเรียกต้องส่งยอดที่ถูกต้องตามงวด)
 */
export function calculateThaiAnnualPIT(netAssessableIncomeAnnual: number): number {
  const n = Math.max(0, netAssessableIncomeAnnual);
  if (n <= 150_000) return 0;
  if (n <= 300_000) return (n - 150_000) * 0.05;
  if (n <= 500_000) return (n - 300_000) * 0.1 + 7_500;
  if (n <= 750_000) return (n - 500_000) * 0.15 + 27_500;
  if (n <= 1_000_000) return (n - 750_000) * 0.2 + 65_000;
  if (n <= 2_000_000) return (n - 1_000_000) * 0.25 + 115_000;
  if (n <= 5_000_000) return (n - 2_000_000) * 0.3 + 365_000;
  return (n - 5_000_000) * 0.35 + 1_265_000;
}

